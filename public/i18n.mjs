const LANGS = { en: null, hi: HI, bn: BN };
const originals = new WeakMap(); // text node -> its English text
let current = 'en';
try { current = localStorage.getItem('aziz-lang') ?? 'en'; } catch { /* Storage may be off. */ }
if (!(current in LANGS)) current = 'en';

function translateNode(node) {
  const parent = node.parentElement;
  if (!parent || ['SCRIPT', 'STYLE', 'TEXTAREA', 'OPTION'].includes(parent.tagName)) return;
  const english = originals.get(node) ?? node.nodeValue.trim();
  const table = LANGS[current];
  const word = table?.[english];
  if (!word) {
    if (originals.has(node) && !table) { node.nodeValue = originals.get(node); originals.delete(node); }
    return;
  }
  if (!originals.has(node)) originals.set(node, english);
  const lead = node.nodeValue.match(/^\s*/)[0];
  const tail = node.nodeValue.match(/\s*$/)[0];
  node.nodeValue = lead + word + tail;
}
function translateTree(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) translateNode(node);
}
function applyAll() {
  // Switching back to English restores every translated node; other switches re-translate from the English text.
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (originals.has(node)) {
      const english = originals.get(node);
      const lead = node.nodeValue.match(/^\s*/)[0];
      const tail = node.nodeValue.match(/\s*$/)[0];
      node.nodeValue = lead + english + tail;
      originals.delete(node);
    }
  }
  if (LANGS[current]) translateTree(document.body);
  document.documentElement.lang = current;
}

const select = document.querySelector('#lang-select');
if (select) {
  select.value = current;
  select.addEventListener('change', () => {
    current = select.value in LANGS ? select.value : 'en';
    try { localStorage.setItem('aziz-lang', current); } catch { /* Storage may be off. */ }
    applyAll();
  });
}
let queued = false;
const pending = new Set();
new MutationObserver((records) => {
  if (!LANGS[current]) return;
  for (const record of records) {
    if (record.type === 'characterData') pending.add(record.target);
    else for (const added of record.addedNodes) pending.add(added);
  }
  if (queued) return;
  queued = true;
  requestAnimationFrame(() => {
    queued = false;
    for (const target of pending) {
      if (target.nodeType === Node.TEXT_NODE) translateNode(target);
      else if (target.nodeType === Node.ELEMENT_NODE) translateTree(target);
    }
    pending.clear();
  });
}).observe(document.body, { childList: true, subtree: true, characterData: true });
if (LANGS[current]) applyAll();
